#!/usr/bin/env python3
"""Generate source/font_data.c: anti-aliased DejaVu Sans Mono glyph cells (8-bit alpha)."""
import os, sys
os.environ.setdefault("PYGAME_HIDE_SUPPORT_PROMPT", "1")
import pygame
pygame.init()
REG = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
BOLD = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
FONTS = [  # name, file, size, first, last
    ("XS", REG, 14, 32, 126), ("S", REG, 17, 32, 126), ("M", REG, 20, 32, 126),
    ("B", BOLD, 22, 32, 126), ("MID", BOLD, 28, 32, 126), ("BIG", BOLD, 46, 32, 126),
    ("HUGE", BOLD, 112, 45, 57),
]
out = ["/* generated by tools/gen_font.py from DejaVu Sans Mono (Bitstream Vera license) */",
       '#include "gfx.h"']
for name, path, size, first, last in FONTS:
    f = pygame.font.Font(path, size)
    cw, ch = f.size("M")
    data = bytearray()
    for code in range(first, last + 1):
        s = pygame.Surface((cw, ch), pygame.SRCALPHA)
        s.fill((0, 0, 0, 0))
        g = f.render(chr(code), True, (255, 255, 255))
        s.blit(g, (0, 0))
        for y in range(ch):
            for x in range(cw):
                data.append(s.get_at((x, y))[3])
    arr = f"F_{name}_DATA"
    lines = []
    for i in range(0, len(data), 40):
        lines.append(",".join(str(b) for b in data[i:i + 40]))
    out.append(f"static const unsigned char {arr}[{len(data)}] = {{\n" + ",\n".join(lines) + "\n};")
    out.append(f"const Font FONT_{name} = {{ {cw}, {ch}, {first}, {last - first + 1}, {arr} }};")
    print(name, size, cw, ch, len(data), file=sys.stderr)
open(sys.argv[1], "w").write("\n".join(out) + "\n")
